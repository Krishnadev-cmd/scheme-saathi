-- Scheme Saathi schema for Postgres / Supabase.
-- Idempotent: safe to run again. Apply with `npm run db:migrate`, the Supabase
-- SQL editor, or `supabase db push`.
--
-- Timestamps are ISO 8601 text (sortable, identical to the SQLite store), and
-- structured values are jsonb.

create table if not exists users (
  id text primary key,                 -- "<channel>:<chat id>"
  channel text not null,
  external_id text not null,
  lang text not null default 'en',
  step text not null default 'language',
  profile jsonb not null default '{}'::jsonb,
  subscribed boolean not null default true,
  last_results jsonb not null default '[]'::jsonb,
  last_inbound_at text,
  consent_at text,
  created_at text not null
);
create index if not exists users_created_at_idx on users (created_at desc);

create table if not exists schemes (
  id text primary key,
  data jsonb not null,
  source text not null,
  open_date text,
  close_date text,
  updated_at text not null
);

create table if not exists notifications (
  user_id text not null,
  scheme_id text not null,
  kind text not null,                  -- 'opened:<window>' | 'closing_soon:<window>'
  sent_at text not null,
  primary key (user_id, scheme_id, kind)
);

create table if not exists source_state (
  url text primary key,
  hash text not null,
  checked_at text not null
);

create table if not exists counters (
  name text primary key,               -- anonymous totals, e.g. consent_declined
  value integer not null default 0
);

create table if not exists broadcasts (
  id integer generated by default as identity primary key,
  created_at text not null,
  finished_at text,
  message jsonb not null,
  audience jsonb not null,
  status text not null,                -- sending | done | error
  total integer not null default 0,
  sent integer not null default 0,
  skipped integer not null default 0
);

create table if not exists pipeline_runs (
  id integer generated by default as identity primary key,
  started_at text not null,
  finished_at text,
  status text not null,
  log text not null default ''
);
-- At most one run can be "running": the run lock.
create unique index if not exists pipeline_runs_one_running on pipeline_runs (status) where status = 'running';

-- Shared across serverless instances: rate limits and webhook de-duplication.
create table if not exists rate_limits (
  key text primary key,
  window_start text not null,
  count integer not null default 0
);

create table if not exists processed_messages (
  id text primary key,                 -- "<channel>:<message id>"
  at text not null
);

-- Supabase exposes the public schema through its REST API. The app connects
-- as the database owner (which bypasses RLS); enabling RLS with no policies
-- blocks the anon and authenticated API roles from reading any of this data.
alter table users enable row level security;
alter table schemes enable row level security;
alter table notifications enable row level security;
alter table source_state enable row level security;
alter table counters enable row level security;
alter table broadcasts enable row level security;
alter table pipeline_runs enable row level security;
alter table rate_limits enable row level security;
alter table processed_messages enable row level security;
